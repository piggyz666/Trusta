import copy
from dataclasses import replace
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch
from cryptography.hazmat.primitives import serialization
from backend.config import Config
from backend.domain import Rejected
from backend.service import TrustaService
from backend.security.did_key import from_public_key,public_key,resolve


class DIDTests(unittest.TestCase):
    def setUp(self):
        self.tmp=tempfile.TemporaryDirectory();self.addCleanup(self.tmp.cleanup)
        self.config=Config(db_path=str(Path(self.tmp.name)/'did.db'),signing_key=b'did-key-test-root',communication_version=3,banking_version=5,did_enabled=True)
        self.s=TrustaService(self.config)

    def test_p256_external_example_and_stateless_roundtrip(self):
        # Public example from GOV.UK Wallet, not generated by this implementation.
        did='did:key:zDnaeSGfSQMYvnLbLWEubhhGDPoq7pA9MMNvumvbsmMCZovUR'
        key=public_key(did)
        pem=key.public_bytes(serialization.Encoding.PEM,serialization.PublicFormat.SubjectPublicKeyInfo).decode()
        self.assertEqual(from_public_key(pem),did)
        document=resolve(did)
        self.assertEqual(document['id'],did)
        self.assertEqual(document['verificationMethod'][0]['publicKeyMultibase'],did[8:])
        self.assertNotIn('keyAgreement',document)

    def test_binding_live_capabilities_tamper_expiry_and_restart(self):
        bundle=self.s.did.export('finance')
        self.assertTrue(self.s.did.verify(bundle))
        self.assertTrue(TrustaService(self.config).did.verify(bundle))
        bad=copy.deepcopy(bundle);bad['binding']['capabilities']['bank'].append('banking.transfer')
        with self.assertRaises(Rejected):self.s.did.verify(bad)
        bad=copy.deepcopy(bundle);bad['binding']['agent_id']='transaction'
        with self.assertRaises(Rejected):self.s.did.verify(bad)
        with patch.object(self.s.crypto_registry,'now',return_value=bundle['binding']['expires_at']):
            with self.assertRaises(Rejected):self.s.did.verify(bundle)
        self.assertEqual(self.s.db.rows('SELECT * FROM transactions'),[])

    def test_rotation_and_revocation_are_registry_semantics(self):
        old=self.s.did.export('transaction')
        new_identity=self.s.crypto_registry.rotate('transaction')
        current=self.s.did.export('transaction')
        self.assertNotEqual(old['binding']['did'],current['binding']['did'])
        self.assertEqual(resolve(old['binding']['did'])['id'],old['binding']['did'])
        with self.assertRaises(Rejected):self.s.did.verify(old)
        self.assertTrue(self.s.did.verify(current))
        self.s.crypto_registry.set_status('transaction','REVOKED')
        with self.assertRaises(Rejected):self.s.did.verify(current)
        # did:key itself cannot be deactivated; it is the live Registry that denies trust.
        self.assertEqual(resolve(current['binding']['did'])['id'],current['binding']['did'])

    def test_bad_identifiers_and_disabled_profile(self):
        for did in ('did:trusta:finance','did:key:z0','did:key:z111','did:key:z6MkhaXgBZDvotDkL5257faiztiGiC2QtKLGpbnnEGta2doK','https://example.org/key'):
            with self.assertRaises(Rejected):resolve(did)
        other=TrustaService(replace(self.config,did_enabled=False))
        with self.assertRaises(Rejected):other.extensions.require('did')
        self.assertTrue(other.extensions.status()['did']['implemented'])
        self.assertFalse(other.crypto_registry.snapshot()['did_implemented']) # V3 envelope still uses the original URN.


if __name__=='__main__':unittest.main()
